/**
 * #231 dedicated, terminating Worker protocol; no general audio transcoding.
 * Real PCM16 WAV sources are strictly parsed, edited and re-encoded locally.
 * Actual output-waveform samples are summarized from the completed WAV bytes.
 */
import { AUDIO_231_MAX_INPUT_BYTES, AUDIO_231_MAX_TOTAL_INPUT_BYTES,
  inspectAudioPcm16Source231, type AudioTimelineEdit231 } from "./timeline-231";
import { renderAudioTimelineDsp231, type AudioDspSettings231,
  type AudioDspPreview231 } from "./timeline-dsp-231";

export interface AudioJob231 {
  readonly kind: "render";
  readonly sources: readonly ArrayBuffer[];
  readonly startSeconds: number;
  readonly endSeconds: number | null;
  readonly secondFirst: boolean;
  readonly gain: number;
  readonly dsp: AudioDspSettings231;
}

export interface AudioJobResult231 {
  readonly kind: "done";
  readonly wav: ArrayBuffer;
  readonly preview: AudioDspPreview231;
  readonly peaks: readonly number[];
}

function fail(code: string, message: string): never { throw new Error(`${code}: ${message}`); }

/** True PCM16 output peak envelope, measured from the final generated bytes. */
export function waveformPeaks231(wav: Uint8Array, bars = 192): number[] {
  if (!Number.isSafeInteger(bars) || bars < 1 || bars > 256 || wav.length < 46) {
    fail("AUDIO_231_WAVEFORM_INPUT", "Invalid WAV or waveform resolution");
  }
  const view = new DataView(wav.buffer, wav.byteOffset, wav.byteLength);
  const tag = (at: number) => String.fromCharCode(wav[at]!, wav[at + 1]!, wav[at + 2]!, wav[at + 3]!);
  const channels = view.getUint16(22, true);
  const rate = view.getUint32(24, true);
  const dataSize = view.getUint32(40, true);
  if (tag(0) !== "RIFF" || tag(8) !== "WAVE" || tag(12) !== "fmt " || tag(36) !== "data" ||
      view.getUint32(4, true) !== wav.length - 8 || view.getUint32(16, true) !== 16 ||
      view.getUint16(20, true) !== 1 || (channels !== 1 && channels !== 2) ||
      rate < 8000 || rate > 48000 || view.getUint16(34, true) !== 16 ||
      view.getUint16(32, true) !== channels * 2 ||
      view.getUint32(28, true) !== rate * channels * 2 ||
      dataSize !== wav.length - 44 || dataSize % (channels * 2) !== 0 || dataSize === 0) {
    fail("AUDIO_231_WAVEFORM_INPUT", "Output is not a strict PCM16 WAV");
  }
  const frames = dataSize / (channels * 2);
  const peaks = new Array<number>(bars).fill(0);
  for (let frame = 0; frame < frames; frame += 1) {
    const bucket = Math.min(bars - 1, Math.floor(frame * bars / frames));
    for (let channel = 0; channel < channels; channel += 1) {
      const value = Math.abs(view.getInt16(44 + (frame * channels + channel) * 2, true)) / 32768;
      peaks[bucket] = Math.max(peaks[bucket]!, value);
    }
  }
  return peaks;
}

/** Pure protocol core, so negative corpus tests run without browser mocks. */
export function renderAudioJob231(job: AudioJob231, signal?: AbortSignal): AudioJobResult231 {
  if (!job || job.kind !== "render" || !Array.isArray(job.sources) ||
      job.sources.length < 1 || job.sources.length > 2 || typeof job.secondFirst !== "boolean" ||
      !Number.isFinite(job.startSeconds) || job.startSeconds < 0 ||
      (job.endSeconds !== null && (!Number.isFinite(job.endSeconds) || job.endSeconds <= job.startSeconds)) ||
      !Number.isFinite(job.gain) || job.gain < 0 || job.gain > 4) {
    fail("AUDIO_231_WORKER_REQUEST", "Malformed PCM timeline job");
  }
  let totalBytes = 0;
  const sources = job.sources.map((buffer) => {
    if (!(buffer instanceof ArrayBuffer) || buffer.byteLength < 44 || buffer.byteLength > AUDIO_231_MAX_INPUT_BYTES) {
      fail("AUDIO_231_INPUT_LIMIT", "One source exceeds allowed RIFF/WAV input bounds");
    }
    totalBytes += buffer.byteLength;
    if (totalBytes > AUDIO_231_MAX_TOTAL_INPUT_BYTES) fail("AUDIO_231_INPUT_LIMIT", "Total source budget exceeded");
    return new Uint8Array(buffer);
  });
  const info = sources.map((source) => inspectAudioPcm16Source231(source, signal));
  const first = info[0]!;
  if (info.some((part) => part.sampleRate !== first.sampleRate || part.channels !== first.channels)) {
    fail("AUDIO_231_LAYOUT_MISMATCH", "Both WAV files must have identical rate and channel layout");
  }
  const begin = Math.round(job.startSeconds * first.sampleRate);
  const end = job.endSeconds === null ? first.frames : Math.round(job.endSeconds * first.sampleRate);
  if (begin < 0 || end > first.frames || end <= begin) {
    fail("AUDIO_231_INVALID_RANGE", "Trim must produce nonempty frames inside first WAV");
  }
  const edit = (sourceIndex: number, startFrame: number, endFrame: number): AudioTimelineEdit231 => ({
    sourceIndex, startFrame, endFrame, gain: job.gain, fadeInFrames: 0, fadeOutFrames: 0,
  });
  const edits = [edit(0, begin, end)];
  if (info[1]) {
    const second = edit(1, 0, info[1].frames);
    if (job.secondFirst) edits.unshift(second);
    else edits.push(second);
  } else if (job.secondFirst) {
    fail("AUDIO_231_WORKER_REQUEST", "Second-first requires two WAV sources");
  }
  const result = renderAudioTimelineDsp231(sources, edits, job.dsp, signal);
  const wav = result.wav.buffer.slice(result.wav.byteOffset, result.wav.byteOffset + result.wav.byteLength) as ArrayBuffer;
  return { kind: "done", wav, preview: result.preview, peaks: waveformPeaks231(result.wav) };
}

if (typeof self !== "undefined" && typeof document === "undefined") {
  self.onmessage = (event: MessageEvent<AudioJob231>) => {
    try {
      const result = renderAudioJob231(event.data);
      self.postMessage(result, { transfer: [result.wav] });
    } catch (error) {
      self.postMessage({ kind: "error", message: error instanceof Error ? error.message : "AUDIO_231_WORKER_FAILED" });
    }
  };
}
