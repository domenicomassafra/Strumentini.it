import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { ToolManifest } from "../src/catalog/manifest";
import { buildGoldQualityIndex, renderGoldQualitySource } from "../src/onboarding/quality";
import { compileCatalog } from "./lib/catalog-compiler";

const checkOnly = process.argv.includes("--check");
const root = resolve(import.meta.dirname, "..");
const toolsRoot = resolve(root, "src/tools");

async function discoverManifests(): Promise<ToolManifest[]> {
  const entries = await readdir(toolsRoot, { withFileTypes: true });
  const manifests: ToolManifest[] = [];
  for (const entry of entries.toSorted((left, right) => left.name.localeCompare(right.name))) {
    if (!entry.isDirectory()) continue;
    const manifestPath = resolve(toolsRoot, entry.name, "manifest.ts");
    try {
      await access(manifestPath);
    } catch {
      continue;
    }
    const imported = await import(`${pathToFileURL(manifestPath).href}?catalog=${Date.now()}`) as {
      default?: ToolManifest;
    };
    if (imported.default === undefined) {
      throw new Error(`${manifestPath}: manifest.ts must default-export its canonical ToolManifest`);
    }
    manifests.push(imported.default);
  }
  return manifests;
}

async function discoverReceipts(directory: string, repositoryRoot: string): Promise<unknown[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const receipts: unknown[] = [];
  for (const entry of entries.toSorted((left, right) => left.name.localeCompare(right.name))) {
    const child = resolve(directory, entry.name);
    if (entry.isDirectory()) receipts.push(...await discoverReceipts(child, repositoryRoot));
    else if (entry.isFile() && entry.name.endsWith(".json")) {
      try {
        const value = JSON.parse(await readFile(child, "utf8")) as unknown;
        if (typeof value === "object" && value !== null && !Array.isArray(value)) {
          receipts.push({ ...value, receiptPath: relative(repositoryRoot, child) });
        } else {
          receipts.push(value);
        }
      } catch {
        continue;
      }
    }
  }
  return receipts;
}

const artifacts = compileCatalog(await discoverManifests());
const qualityResult = buildGoldQualityIndex(
  await discoverReceipts(resolve(root, "quality/receipts"), root),
  artifacts.summaries.map(({ id }) => id),
);

const catalogSource = `// AUTO-GENERATED by scripts/build-catalog.ts. Do not edit.\n` +
  `import type { ToolSummary } from "../catalog/manifest";\n\n` +
  `export const catalog = ${JSON.stringify(artifacts.summaries, null, 2)} as const satisfies readonly ToolSummary[];\n`;

const loaderLines = artifacts.loaders.map(
  ({ id, implementation }) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(implementation)}),`,
);
const loadersSource = `// AUTO-GENERATED by scripts/build-catalog.ts. Do not edit.\n` +
  `import type { ToolModule } from "../runtime/types";\n\n` +
  `export const toolLoaders: Readonly<Record<string, () => Promise<{ default: ToolModule }>>> = {\n${loaderLines.join("\n")}\n};\n`;
const qualitySource = renderGoldQualitySource(qualityResult.index);

const outputs = [
  [resolve(root, "src/generated/catalog.ts"), catalogSource],
  [resolve(root, "src/generated/tool-loaders.ts"), loadersSource],
  [resolve(root, "src/generated/quality.ts"), qualitySource],
] as const;

for (const [path, content] of outputs) {
  if (checkOnly) {
    const existing = await readFile(path, "utf8").catch(() => "");
    if (existing !== content) {
      console.error(`catalog output is stale: ${path}`);
      process.exitCode = 1;
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
  }
}

if (process.exitCode !== 1) {
  console.log(`catalog: ${artifacts.summaries.length} tool(s), Gold receipts ${qualityResult.index.tools.length}, outputs ${checkOnly ? "current" : "generated"}`);
}
