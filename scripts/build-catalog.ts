import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { businessDayManifest } from "../src/tools/business-day/manifest";
import { compileCatalog } from "./lib/catalog-compiler";

const checkOnly = process.argv.includes("--check");
const artifacts = compileCatalog([businessDayManifest]);
const root = resolve(import.meta.dirname, "..");

const catalogSource = `// AUTO-GENERATED by scripts/build-catalog.ts. Do not edit.\n` +
  `import type { ToolSummary } from "../catalog/manifest";\n\n` +
  `export const catalog = ${JSON.stringify(artifacts.summaries, null, 2)} as const satisfies readonly ToolSummary[];\n`;

const loaderLines = artifacts.loaders.map(
  ({ id, implementation }) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(implementation)}),`,
);
const loadersSource = `// AUTO-GENERATED by scripts/build-catalog.ts. Do not edit.\n` +
  `import type { ToolModule } from "../runtime/types";\n\n` +
  `export const toolLoaders: Readonly<Record<string, () => Promise<{ default: ToolModule }>>> = {\n${loaderLines.join("\n")}\n};\n`;

const outputs = [
  [resolve(root, "src/generated/catalog.ts"), catalogSource],
  [resolve(root, "src/generated/tool-loaders.ts"), loadersSource],
] as const;

for (const [path, content] of outputs) {
  if (checkOnly) {
    const existing = await readFile(path, "utf8").catch(() => "");
    if (existing !== content) {
      console.error(`catalog output is stale: ${path}`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(path, content, "utf8");
  }
}

if (process.exitCode !== 1) {
  console.log(`catalog: ${artifacts.summaries.length} tool(s), outputs ${checkOnly ? "current" : "generated"}`);
}
