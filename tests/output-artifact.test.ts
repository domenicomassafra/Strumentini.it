import { describe, expect, it } from "vitest";
import { createOutputArtifactDescriptor } from "../src/runtime/output-artifact";

describe("typed output artifact descriptor", () => {
  it("carries authoritative bytes and enables download only after matching verification", () => {
    const bytes = new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2d]);
    const artifact = createOutputArtifactDescriptor({
      kind: "pdf",
      name: "report.pdf",
      mime: "application/pdf",
      bytes,
      verification: {
        state: "verified",
        verifiedMime: "application/pdf",
        method: "PDF header and parser reopen",
        signature: "%PDF-",
      },
      fidelity: "structural",
      fidelityNote: "Page structure was preserved by the generating operation.",
    });

    expect(artifact.byteLength).toBe(bytes.byteLength);
    expect(artifact.bytes).toBe(bytes);
    expect(artifact.issues).toEqual([]);
    expect(artifact.download).toEqual({ filename: "report.pdf", mime: "application/pdf", ready: true });
  });

  it("downgrades a MIME or extension mismatch to a visible warning and blocks download-ready truth", () => {
    const artifact = createOutputArtifactDescriptor({
      kind: "image",
      name: "result.png",
      mime: "image/png",
      bytes: new Uint8Array([0xff, 0xd8, 0xff]),
      verification: {
        state: "verified",
        verifiedMime: "image/jpeg",
        method: "magic bytes",
        signature: "FFD8FF",
      },
      fidelity: "lossy",
      fidelityNote: "The image was re-encoded.",
    });

    expect(artifact.verification.state).toBe("warning");
    expect(artifact.issues.join(" ")).toMatch(/does not match verified MIME/u);
    expect(artifact.download.ready).toBe(false);
  });

  it("keeps unverified and malformed artifacts from being presented as verified downloads", () => {
    const unverified = createOutputArtifactDescriptor({
      kind: "text",
      name: "notes.txt",
      mime: "text/plain",
      bytes: new TextEncoder().encode("hello"),
      verification: { state: "unverified" },
      fidelity: "lossless",
      fidelityNote: "Exact UTF-8 text bytes from the result.",
    });
    expect(unverified.download.ready).toBe(false);

    const malformed = createOutputArtifactDescriptor({
      kind: "structured",
      name: "data.json",
      mime: "application/json",
      bytes: new TextEncoder().encode("{broken"),
      verification: { state: "invalid", message: "JSON parser rejected the generated bytes." },
      fidelity: "structural",
      fidelityNote: "Structured JSON output was requested.",
    });
    expect(malformed.verification.state).toBe("invalid");
    expect(malformed.download.ready).toBe(false);
  });

  it("supports generic file output while requiring measured verification facts for ready downloads", () => {
    const artifact = createOutputArtifactDescriptor({
      kind: "file",
      name: "archive.bin",
      mime: "application/octet-stream",
      bytes: new Uint8Array([1, 2, 3]),
      verification: {
        state: "verified",
        verifiedMime: "application/octet-stream",
        method: "producer format contract and byte-length check",
      },
      fidelity: "unknown",
      fidelityNote: "No semantic fidelity claim is made for this generic file.",
    });
    expect(artifact.download.ready).toBe(true);
  });
});
