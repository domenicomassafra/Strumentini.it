import { spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { OFFICE_368_FIXTURES, inspectOoxml368 } from "../scripts/audit-office-fidelity-368";

const root = resolve(import.meta.dirname, "..");
const spike = resolve(root, "spikes/heavy-local-feasibility");
const Zip = createRequire(resolve(spike, "package.json"))("jszip") as {
  loadAsync: (bytes: Buffer) => Promise<{
    files: Record<string, unknown>;
    file: (name: string, data?: string | Buffer) => { async: (type: "string" | "nodebuffer") => Promise<string | Buffer> } | null;
    folder: (name: string) => unknown;
    generateAsync: (options: { type: "nodebuffer"; compression: "DEFLATE" }) => Promise<Buffer>;
  }>;
};

async function original(kind: keyof typeof OFFICE_368_FIXTURES): Promise<Buffer> {
  const fixture = OFFICE_368_FIXTURES[kind];
  const bytes = await readFile(resolve(root, fixture.relativePath));
  expect(bytes.length).toBe(fixture.bytes);
  expect(createHash("sha256").update(bytes).digest("hex")).toBe(fixture.sha256);
  return bytes;
}

/** Mutate only disposable generated bytes, matching ZIP local and central names. */
function rawCentralRecords(buffer: Buffer): Array<{ name: string; offset: number; local: number }> {
  const end = buffer.length - 22;
  expect(buffer.readUInt32LE(end)).toBe(0x06054b50);
  let position = buffer.readUInt32LE(end + 16);
  const count = buffer.readUInt16LE(end + 10);
  const records: Array<{ name: string; offset: number; local: number }> = [];
  for (let i = 0; i < count; i++) {
    expect(buffer.readUInt32LE(position)).toBe(0x02014b50);
    const size = buffer.readUInt16LE(position + 28);
    records.push({
      name: buffer.toString("utf8", position + 46, position + 46 + size),
      offset: position,
      local: buffer.readUInt32LE(position + 42),
    });
    position += 46 + size + buffer.readUInt16LE(position + 30) + buffer.readUInt16LE(position + 32);
  }
  expect(position).toBe(end);
  return records;
}

function duplicateName(archive: Buffer, from: string, to: string): Buffer {
  expect(Buffer.byteLength(from)).toBe(Buffer.byteLength(to));
  const part = rawCentralRecords(archive).find((entry) => entry.name === from);
  expect(part).toBeDefined();
  expect(archive.readUInt32LE(part!.local)).toBe(0x04034b50);
  expect(archive.toString("utf8", part!.local + 30, part!.local + 30 + from.length)).toBe(from);
  archive.write(to, part!.offset + 46, "utf8");
  archive.write(to, part!.local + 30, "utf8");
  return archive;
}

function independentPython(archive: Buffer, script: string): unknown {
  const result = spawnSync("python3", ["-c", script], { input: archive, encoding: "utf8" });
  expect(result.error).toBeUndefined();
  expect(result.status, result.stderr).toBe(0);
  return JSON.parse(result.stdout.trim()) as unknown;
}

describe("#368 raw central directory must not be erased by JSZip map semantics", () => {
  it("refuses duplicate XLSX relationship members when JSZip hides a real external target", async () => {
    const zip = await Zip.loadAsync(await original("xlsx"));
    const visible = "xl/worksheets/_rels/sheet1.xml.rels";
    const shadow = "xl/worksheets/_rels/sheet2.xml.rels";
    const xml = await zip.file(visible)!.async("string") as string;
    expect(xml).toContain('TargetMode="External"');
    const inert = xml.replace(/<Relationship\b[^>]*\bTargetMode="External"[^>]*\/>/u, "");
    expect(inert).not.toContain('TargetMode="External"');
    zip.file(shadow, inert);
    const bytes = duplicateName(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }), shadow, visible);
    expect(independentPython(bytes, `
import io,json,sys,zipfile,xml.etree.ElementTree as ET
z=zipfile.ZipFile(io.BytesIO(sys.stdin.buffer.read()))
parts=[p for p in z.infolist() if p.filename=="xl/worksheets/_rels/sheet1.xml.rels"]
print(json.dumps([sum(n.get("TargetMode")=="External" for n in ET.fromstring(z.open(p).read())) for p in parts]))
`)).toEqual([1, 0]);
    const jszip = await Zip.loadAsync(bytes);
    expect(Object.keys(jszip.files).filter((name) => name === visible)).toHaveLength(1);
    await expect(inspectOoxml368(bytes, "xlsx", spike)).rejects.toThrow(/DUPLICATE/u);
  });

  it("refuses a duplicate DOCX part whose ignored original has a corrupt central CRC", async () => {
    const zip = await Zip.loadAsync(await original("docx"));
    const visible = "word/document.xml";
    const shadow = "word/hidden__.xml";
    zip.file(shadow, await zip.file(visible)!.async("nodebuffer") as Buffer);
    const bytes = duplicateName(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }), shadow, visible);
    const first = rawCentralRecords(bytes).find((entry) => entry.name === visible)!;
    bytes.writeUInt32LE((bytes.readUInt32LE(first.offset + 16) ^ 1) >>> 0, first.offset + 16);
    expect(independentPython(bytes, `
import io,json,sys,zipfile
z=zipfile.ZipFile(io.BytesIO(sys.stdin.buffer.read()))
parts=[p for p in z.infolist() if p.filename=="word/document.xml"]
bad=False
try: z.open(parts[0]).read()
except zipfile.BadZipFile: bad=True
print(json.dumps({"parts":len(parts),"bad_crc":bad}))
`)).toEqual({ parts: 2, bad_crc: true });
    await expect(inspectOoxml368(bytes, "docx", spike)).rejects.toThrow(/DUPLICATE/u);
  });

  it("counts 9,000 raw directory entries against the advertised 256-member limit", async () => {
    const zip = await Zip.loadAsync(await original("docx"));
    for (let index = 0; index < 9000; index++) zip.folder(`unused/${String(index).padStart(5, "0")}`);
    const bytes = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    expect(bytes.length).toBeLessThan(2_097_152);
    expect(independentPython(bytes, `
import io,json,sys,zipfile
z=zipfile.ZipFile(io.BytesIO(sys.stdin.buffer.read()))
print(json.dumps({"total":len(z.infolist()),"dirs":sum(p.is_dir() for p in z.infolist())}))
`)).toMatchObject({ total: 9020, dirs: 9001 });
    await expect(inspectOoxml368(bytes, "docx", spike)).rejects.toThrow(/ZIP_ENTRY_LIMIT/u);
  }, 30_000);

  it("allows 256 raw members including directories, then refuses the 257th", async () => {
    const zip = await Zip.loadAsync(await original("docx"));
    for (let index = 0; index < 236; index++) zip.folder(`limit/${String(index).padStart(3, "0")}`);
    const allowed = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    expect(rawCentralRecords(allowed)).toHaveLength(256);
    expect((await inspectOoxml368(allowed, "docx", spike)).kind).toBe("docx");
    zip.folder("limit/236");
    const blocked = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    expect(rawCentralRecords(blocked)).toHaveLength(257);
    await expect(inspectOoxml368(blocked, "docx", spike)).rejects.toThrow(/ZIP_ENTRY_LIMIT/u);
  });

  it("refuses a Unicode-normalization alias before interpreting Office parts", async () => {
    const zip = await Zip.loadAsync(await original("docx"));
    zip.file("ｗord/document.xml", await zip.file("word/document.xml")!.async("nodebuffer") as Buffer);
    const bytes = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    expect(rawCentralRecords(bytes).filter((record) => record.name.endsWith("document.xml"))).toHaveLength(2);
    await expect(inspectOoxml368(bytes, "docx", spike)).rejects.toThrow(/DUPLICATE/u);
  });
});
