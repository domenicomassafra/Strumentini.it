import { beforeAll, describe, expect, it } from "vitest";
import { zipSync } from "fflate";
import {
  OUTPUT_408_MAX_BYTES,
  OUTPUT_408_MAX_EXPANDED_BYTES,
  generateOutputSamples408,
  outputConsumerMatrix408,
  verifyOutputConsumer408,
  type Output408,
} from "../scripts/verify-output-consumers-408";

let samples: Output408[];
const encoder = new TextEncoder();

function replace(source: Output408, change: Partial<Output408>): Output408 {
  return { ...source, ...change };
}

beforeAll(async () => { samples = await generateOutputSamples408(); }, 60_000);

describe("#408 independent consumer oracle, scoped offline binary evidence", () => {
  it("reopens REAL outputs for PDF PNG CSV DOCX XLSX WAV through different consumers", async () => {
    expect(samples.map((sample) => sample.format)).toEqual(["pdf", "png", "csv", "docx", "xlsx", "wav"]);
    for (const sample of samples) {
      const result = await verifyOutputConsumer408(sample);
      expect(result.status, `${sample.format}: ${result.status === "PASS" ? "" : result.reason}`).toBe("PASS");
      if (result.status !== "PASS") continue;
      expect(result.byteLength).toBe(sample.bytes.length);
      expect(result.sha256).toMatch(/^[a-f0-9]{64}$/u);
      expect(result.oracle).toBeTruthy();
      expect(Object.keys(result.facts).length).toBeGreaterThan(0);
    }
  }, 60_000);

  it("fails closed for wrong MIME and extension, despite valid generated bytes", async () => {
    for (const output of samples) {
      const wrongMime = await verifyOutputConsumer408(replace(output, { mime: "application/octet-stream" }));
      expect(wrongMime).toMatchObject({ status: "FAIL", format: output.format });
      if (wrongMime.status === "FAIL") expect(wrongMime.reason).toContain("WRONG_MIME");
      const wrongName = await verifyOutputConsumer408(replace(output, { filename: "lies.txt" }));
      expect(wrongName).toMatchObject({ status: "FAIL", format: output.format });
      if (wrongName.status === "FAIL") expect(wrongName.reason).toContain("WRONG_EXTENSION");
    }
  });

  it("refuses empty, header-only, missing EOF and truncated producer binaries", async () => {
    for (const output of samples) {
      for (const bytes of [new Uint8Array(), output.bytes.slice(0, 2)]) {
        const result = await verifyOutputConsumer408(replace(output, { bytes }));
        expect(result.status, output.format).toBe("FAIL");
      }
      // CSV can legally omit a final line break; use an incomplete quoted field
      // as its semantically definite truncated case, not a guess.
      const truncated = output.format === "csv"
        ? encoder.encode('id,label\n000123,"partial')
        // PDF trailing line break is optional in the file format; truncating
        // that alone is not a corrupt PDF. Remove the actual EOF marker.
        : output.format === "pdf" ? output.bytes.slice(0, -7)
        : output.bytes.slice(0, -1);
      const result = await verifyOutputConsumer408(replace(output, { bytes: truncated }));
      expect(result.status, `${output.format} truncated`).toBe("FAIL");
    }
  }, 60_000);

  it("refuses actual bytes mislabeled as another nominally valid family", async () => {
    const pdf = samples.find((sample) => sample.format === "pdf")!;
    const png = samples.find((sample) => sample.format === "png")!;
    const docx = samples.find((sample) => sample.format === "docx")!;
    const xlsx = samples.find((sample) => sample.format === "xlsx")!;
    expect((await verifyOutputConsumer408(replace(pdf, { bytes: png.bytes }))).status).toBe("FAIL");
    expect((await verifyOutputConsumer408(replace(png, { bytes: pdf.bytes }))).status).toBe("FAIL");
    expect((await verifyOutputConsumer408(replace(xlsx, { bytes: docx.bytes }))).status).toBe("FAIL");
    expect((await verifyOutputConsumer408(replace(docx, { bytes: xlsx.bytes }))).status).toBe("FAIL");
    expect((await verifyOutputConsumer408(replace(samples.find((sample) => sample.format === "csv")!, { bytes: png.bytes }))).status).toBe("FAIL");
  });

  it("fails closed on oversized inputs and ZIP expansion bombs without allocating expanded contents", async () => {
    for (const output of samples) {
      const tooBig = replace(output, { bytes: new Uint8Array(OUTPUT_408_MAX_BYTES + 1) });
      const result = await verifyOutputConsumer408(tooBig);
      expect(result.status, output.format).toBe("FAIL");
      if (result.status === "FAIL") expect(result.reason).toContain("BYTE_BUDGET_EXCEEDED");
    }
    // 8 MiB+ compressed to a tiny input; the declared size must be rejected
    // *before* zip inflation by our central-directory preflight.
    const bomb = zipSync({
      "[Content_Types].xml": encoder.encode("a"),
      "word/document.xml": new Uint8Array(OUTPUT_408_MAX_EXPANDED_BYTES + 1),
    }, { level: 9 });
    const docx = samples.find((sample) => sample.format === "docx")!;
    const result = await verifyOutputConsumer408(replace(docx, { bytes: bomb }));
    expect(result.status).toBe("FAIL");
    if (result.status === "FAIL") expect(result.reason).toMatch(/ZIP_MEMBER_RESOURCE_LIMIT|ZIP_CUMULATIVE_EXPANSION_LIMIT/u);
  });

  it("rejects CRC tampering even when ZIP metadata/EOCD remain plausible", async () => {
    for (const kind of ["docx", "xlsx"] as const) {
      const sample = samples.find((value) => value.format === kind)!;
      const corrupt = sample.bytes.slice();
      // Change central-directory CRC, not the bytes of the ZIP footer: this
      // case often passes simple magic/zip-entry tests but must fail the gate.
      let central = -1;
      for (let i = 0; i < corrupt.length - 46; i++) {
        if (corrupt[i] === 0x50 && corrupt[i + 1] === 0x4b && corrupt[i + 2] === 0x01 && corrupt[i + 3] === 0x02) {
          central = i; break;
        }
      }
      if (central < 0 || central + 16 >= corrupt.length) {
        throw new Error(`${kind}: expected a bounded ZIP central-directory CRC field`);
      }
      corrupt[central + 16] = corrupt[central + 16]! ^ 0xff;
      const result = await verifyOutputConsumer408(replace(sample, { bytes: corrupt }));
      expect(result.status, kind).toBe("FAIL");
      if (result.status === "FAIL") expect(result.reason).toMatch(/ZIP_CRC_OR_UNCOMPRESSED_LENGTH_MISMATCH/u);
    }
  });

  it("refuses CSV malformed quoting, binary/control payload, ragged rows, and invalid UTF-8", async () => {
    const source = samples.find((value) => value.format === "csv")!;
    for (const bytes of [
      encoder.encode('id,label\n123,"missing end'),
      encoder.encode('id,label\n123,"ok"evil'),
      encoder.encode('id,label\n123'),
      encoder.encode('id,label\n123,\u0000hidden'),
      Uint8Array.from([0xff, 0xfe, 0x00, 0x01]),
    ]) {
      expect((await verifyOutputConsumer408(replace(source, { bytes }))).status).toBe("FAIL");
    }
  });

  it("measures fixture source output only and labels external application/device checks NOT_RUN", async () => {
    const matrix = await outputConsumerMatrix408();
    expect(matrix).toMatchObject({ ticket: 408, mode: "OFFLINE_SOURCE_ONLY", gate: "PASS_LOCAL" });
    expect(matrix.results).toHaveLength(6);
    expect(matrix.results.every((item) => item.status === "PASS")).toBe(true);
    expect(matrix.externalOracles.length).toBeGreaterThanOrEqual(3);
    expect(matrix.externalOracles.every((item) => item.status === "NOT_RUN")).toBe(true);
    expect(JSON.stringify(matrix)).not.toMatch(/GOLD|DEPLOYED|production-release-passed/u);
  }, 60_000);
});
