"""Extend true #264 Office-library fixtures with editable charts, tables and links.

The images stay in the packages; DOCX, PPTX and XLSX remain genuine files
generated/opened by Office libraries. No Office XML is generated by hand.
"""
from pathlib import Path
from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt
from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE
from pptx.util import Inches
import xlsxwriter
from zipfile import ZipFile

HERE = Path(__file__).parent
ORIGINAL = HERE / "ooxml-media-fixtures"
TARGET = HERE / "ooxml-68-corpus"
TARGET.mkdir(exist_ok=True)

doc = Document(ORIGINAL / "embedded.docx")
doc.add_heading("Office chart and editability regression", level=2)
table = doc.add_table(rows=2, cols=2)
table.cell(0, 0).text = "Quarter"
table.cell(0, 1).text = "Value"
table.cell(1, 0).text = "Q1"
table.cell(1, 1).text = "264"
run = doc.add_paragraph().add_run("Font style survives compression")
run.font.name = "Liberation Serif"
run.font.size = Pt(11)
paragraph = doc.add_paragraph("External reference (inert): ")
relation = paragraph.part.relate_to(
    "https://example.invalid/office-no-fetch",
    "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink",
    is_external=True,
)
hyperlink = OxmlElement("w:hyperlink")
hyperlink.set(qn("r:id"), relation)
text_run = OxmlElement("w:r")
text_node = OxmlElement("w:t")
text_node.text = "Source"
text_run.append(text_node)
hyperlink.append(text_run)
paragraph._p.append(hyperlink)
doc.save(TARGET / "complex.docx")

pres = Presentation(ORIGINAL / "embedded.pptx")
slide = pres.slides[0]
chart_data = CategoryChartData()
chart_data.categories = ["Q1", "Q2", "Q3"]
chart_data.add_series("Editable series", [10, 23, 31])
slide.shapes.add_chart(XL_CHART_TYPE.COLUMN_CLUSTERED, Inches(0.5), Inches(4.5), Inches(4.5), Inches(2), chart_data)
textbox = slide.shapes.add_textbox(Inches(5), Inches(4.8), Inches(3), Inches(0.6))
textbox.text_frame.text = "Fonts and text remain editable"
pres.save(TARGET / "complex.pptx")

book = xlsxwriter.Workbook(TARGET / "complex.xlsx")
sheet = book.add_worksheet("Sales")
sheet.write_row(0, 0, ["Quarter", "Value"])
for row, (quarter, value) in enumerate([("Q1", 10), ("Q2", 23), ("Q3", 31)], 1):
    sheet.write_row(row, 0, [quarter, value])
sheet.write_url("D1", "https://example.invalid/office-no-fetch", string="Reference")
sheet.write("D2", "Editable format", book.add_format({"font_name": "Liberation Serif", "bold": True}))
sheet.insert_image("F2", str(ORIGINAL / "media-original.png"), {"x_scale": 0.5, "y_scale": 0.5})
sheet.insert_image("P2", str(ORIGINAL / "media-original.jpg"), {"x_scale": 0.5, "y_scale": 0.5})
chart = book.add_chart({"type": "column"})
chart.add_series({"categories": "=Sales!$A$2:$A$4", "values": "=Sales!$B$2:$B$4"})
sheet.insert_chart("A7", chart)
book.close()

for extension in ["docx", "pptx", "xlsx"]:
    target = TARGET / f"complex.{extension}"
    with ZipFile(target) as archive:
        names = archive.namelist()
        print(extension, target.stat().st_size, "bytes", len(names), "members", len([p for p in names if "/media/" in p]), "media")
